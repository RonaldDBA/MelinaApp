results = []


def log(ok, msg):
    results.append((ok, msg))
    print(('  ✔ ' if ok else '  ✘ ') + msg, flush=True)


def check(cond, msg):
    log(bool(cond), msg)
    if not cond:
        raise AssertionError(msg)


def start_server(port, data_dir):
    # IMAGE_PROVIDER=mock: simulated provider, to exercise the art workshop without calling any API
    # PACKS_DIR: art packs in a temporary folder, never in assets/packs-inbox
    env = dict(os.environ, PORT=str(port), DATA_DIR=data_dir, PACKS_DIR=os.path.join(data_dir, 'packs'), MELINA_SKIP_ENV_FILE='1', IMAGE_PROVIDER='mock', ANTHROPIC_API_KEY='')
    # Runs the SAME file that iniciar.bat uses on the family computer (bundled server).
    p = subprocess.Popen([plat.node_exe(), '--disable-warning=ExperimentalWarning', str(ROOT / 'apps' / 'server' / 'dist' / 'server.mjs')], cwd=tempfile.gettempdir(), env=env,
                         stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, **plat.popen_kwargs())
    for _ in range(60):
        try:
            with urllib.request.urlopen(f'http://127.0.0.1:{port}/api/health', timeout=1) as r:
                if json.load(r)['ok']:
                    return p
        except Exception:
            time.sleep(0.25)
    raise RuntimeError('server did not start')


def stop_server(p):
    plat.stop_process(p)


def synthetic_image(path, text):
    from PIL import Image, ImageDraw, ImageFont
    im = Image.new('RGB', (640, 260), 'white')
    d = ImageDraw.Draw(im)
    f = None
    for font in plat.FONT_CANDIDATES:
        try:
            f = ImageFont.truetype(font, 96)
            break
        except Exception:
            pass
    f = f or ImageFont.load_default()
    d.line([(10, 220), (630, 220)], fill=(150, 150, 210), width=3)
    d.text((30, 70), text, fill=(25, 25, 90), font=f)
    im.save(path, 'JPEG', quality=88)


def expected_answer(db_file, mode='paper'):
    con = sqlite3.connect(db_file)
    row = con.execute("SELECT id, snapshot_json FROM assignments WHERE status NOT IN ('confirmed','cancelled') AND input_mode = ? ORDER BY created_at DESC LIMIT 1", (mode,)).fetchone()
    con.close()
    ex = json.loads(row[1])['expected']
    if ex['type'] == 'number':
        return str(ex['value'])
    if ex['type'] == 'sequence':
        return ', '.join(str(v) for v in ex['values'])
    if ex['type'] == 'word':
        return ex['value']
    return ex['display']


@contextlib.contextmanager
def failure_snapshot(diag):
    """If a step fails (e.g. a click that hangs), saves the screen and the page console BEFORE the browser closes."""
    try:
        yield
    except Exception:
        p = diag.get('page')
        if p is not None:
            try:
                p.screenshot(path=str(OUT / 'FAILURE.png'))
                (OUT / 'FAILURE.txt').write_text('\n'.join(diag['console'][-80:]) + f'\n\nURL: {p.url}\n', encoding='utf-8')
                print('     failure diagnostics saved to', OUT / 'FAILURE.png', 'and FAILURE.txt')
            except Exception as e:  # the diagnostics never hide the original error
                print('     (could not save the diagnostics:', e, ')')
        raise


