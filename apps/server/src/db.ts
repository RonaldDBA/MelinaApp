export function openDatabase(file: string): DB {
  const db = new DatabaseSync(file);
  db.exec('PRAGMA foreign_keys = ON; PRAGMA journal_mode = WAL; PRAGMA busy_timeout = 5000; PRAGMA synchronous = NORMAL;');
  migrate(db);
  return db;
}

export function migrate(db: DB): number[] {
  db.exec('CREATE TABLE IF NOT EXISTS schema_migrations (version INTEGER PRIMARY KEY, name TEXT NOT NULL, applied_at TEXT NOT NULL)');
  const applied = new Set(
    (db.prepare('SELECT version FROM schema_migrations').all() as Array<{ version: number }>).map((r) => r.version),
  );
  const done: number[] = [];
  for (const m of migrations) {
    if (applied.has(m.version)) continue;
    // recreating a table requires foreign keys turned off OUTSIDE the transaction; at the end, everything is checked
    if (m.rebuild) db.exec('PRAGMA foreign_keys = OFF');
    try {
      tx(db, () => {
        db.exec(m.sql);
        if (m.rebuild) {
          const broken = db.prepare('PRAGMA foreign_key_check').all();
          if (broken.length) throw new Error(`Migration ${m.version}: ${broken.length} broken reference(s); nothing was changed.`);
        }
        db.prepare('INSERT INTO schema_migrations (version, name, applied_at) VALUES (?, ?, ?)').run(m.version, m.name, new Date().toISOString());
      });
    } finally {
      if (m.rebuild) db.exec('PRAGMA foreign_keys = ON');
    }
    done.push(m.version);
  }
  return done;
}

export function pendingMigrations(db: DB): number {
  const row = db.prepare('SELECT MAX(version) AS v FROM schema_migrations').get() as { v: number | null } | undefined;
  return migrations.filter((m) => m.version > (row?.v ?? 0)).length;
}

let depth = 0;
/** Synchronous transaction (node:sqlite is synchronous, so requests cannot interleave). */
export function tx<T>(db: DB, fn: () => T): T {
  if (depth > 0) return fn();
  // BEGIN before marking the depth: if it fails (database busy with another process), the following
  // transactions must not keep running in autocommit. If an old transaction was left open (failed ROLLBACK),
  // roll it back and try again, instead of failing forever with «transaction within a transaction».
  try {
    db.exec('BEGIN IMMEDIATE');
  } catch (e) {
    if (!(db as unknown as { isTransaction?: boolean }).isTransaction) throw e;
    db.exec('ROLLBACK');
    db.exec('BEGIN IMMEDIATE');
  }
  depth++;
  try {
    const r = fn();
    db.exec('COMMIT');
    return r;
  } catch (e) {
    try {
      db.exec('ROLLBACK');
    } catch {
      // SQLite has already rolled the transaction back (the error that matters is the original one); if it is still open,
      // try again, so the following ones do not fail with «transaction within a transaction»
      if ((db as unknown as { isTransaction?: boolean }).isTransaction) {
        try {
          db.exec('ROLLBACK');
        } catch {
          /* nothing more to do */
        }
      }
    }
    throw e;
  } finally {
    depth--;
  }
}
